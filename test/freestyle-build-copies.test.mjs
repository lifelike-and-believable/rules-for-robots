// One isFreestyle for every plugin (docs/specs/freestyle.md, AC-3): npm run build copies
// plugins/core/scripts/freestyle-lib.mjs into each plugin with hooks, and npm run build:check fails
// when a copy differs from its source.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { LIB_COPIES, checkLibCopies, renderLib } from '../build/build.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const SOURCE = path.join(ROOT, 'plugins', 'core', 'scripts', 'freestyle-lib.mjs');

test('freestyle#AC-3: the build copies freestyle-lib.mjs from rfr-core into rfr-web, rfr-unreal, rfr-android, and rfr-process', () => {
  const copies = LIB_COPIES.filter(c => c.src === SOURCE);
  assert.deepEqual(copies.map(c => path.relative(ROOT, c.dest).split(path.sep).join('/')).sort(), ['android', 'process', 'unreal', 'web'].map(p => `plugins/${p}/scripts/freestyle-lib.mjs`));
  // The committed copies are current, and say where they come from.
  assert.deepEqual(checkLibCopies(copies), []);
  for (const c of copies) assert.match(fs.readFileSync(c.dest, 'utf8'), /^\/\/ Generated by npm run build from plugins\/core\/scripts\/freestyle-lib\.mjs\. Edit that file, not this one\.\n/);
});

test('freestyle#AC-3: the build check reports a copy that differs from its source, and one that is missing', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rfr-freestyle-copies-'));
  const changed = path.join(dir, 'changed.mjs');
  const missing = path.join(dir, 'missing.mjs');
  const current = path.join(dir, 'current.mjs');
  fs.writeFileSync(changed, renderLib(SOURCE).replace('isFreestyle', 'isFreestyleChanged'));
  fs.writeFileSync(current, renderLib(SOURCE));
  const problems = checkLibCopies([
    { src: SOURCE, dest: changed, label: 'changed copy' },
    { src: SOURCE, dest: missing, label: 'missing copy' },
    { src: SOURCE, dest: current, label: 'current copy' },
  ]);
  assert.equal(problems.length, 2);
  assert.match(problems[0], /changed\.mjs: stale \(run npm run build\)$/);
  assert.match(problems[1], /missing\.mjs: missing \(run npm run build\)$/);
});
